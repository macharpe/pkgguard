/**
 * Placeholder substitution for the committed wrangler.jsonc templates.
 * Committed templates carry format-valid placeholders; real values come from the
 * environment or .deploy.env. A deploy that still carries a placeholder must fail.
 */

export interface Field {
  /** Environment variable that supplies the real value. */
  env: string;
  /** Format-valid value committed in the template. */
  placeholder: string;
  /** Field-specific format check for the real value. */
  pattern: RegExp;
  hint: string;
}

const FIELDS = {
  ACCOUNT_ID: {
    env: "PKGGUARD_ACCOUNT_ID",
    placeholder: "0".repeat(32),
    pattern: /^[0-9a-f]{32}$/,
    hint: "32 lowercase hex characters",
  },
  KV_ID: {
    env: "PKGGUARD_KV_ID",
    placeholder: `${"0".repeat(31)}1`,
    pattern: /^[0-9a-f]{32}$/,
    hint: "32 lowercase hex characters",
  },
  D1_ID: {
    env: "PKGGUARD_D1_ID",
    placeholder: "00000000-0000-0000-0000-000000000000",
    pattern: /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/,
    hint: "a lowercase UUID",
  },
  ADMIN_HOSTNAME: {
    env: "PKGGUARD_ADMIN_HOSTNAME",
    placeholder: "pkgguard.example.com",
    pattern: /^(?=.{4,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/,
    hint: "a dotted lowercase hostname",
  },
  TEAM_DOMAIN: {
    env: "PKGGUARD_TEAM_DOMAIN",
    placeholder: "your-team.cloudflareaccess.com",
    pattern: /^[a-z0-9][a-z0-9-]*\.cloudflareaccess\.com$/,
    hint: "<team>.cloudflareaccess.com",
  },
  ACCESS_AUD: {
    env: "PKGGUARD_ACCESS_AUD",
    placeholder: "0".repeat(64),
    pattern: /^[0-9a-f]{64}$/,
    hint: "64 lowercase hex characters",
  },
} as const satisfies Record<string, Field>;

export type FieldName = keyof typeof FIELDS;
export const FIELD_NAMES = Object.keys(FIELDS) as FieldName[];
export const field = (name: FieldName): Field => FIELDS[name];

/** Expected occurrences of each placeholder per worker template. A different count means template drift. */
export const WORKERS: Record<string, Partial<Record<FieldName, number>>> = {
  filter: { ACCOUNT_ID: 1, KV_ID: 1, D1_ID: 1 },
};

const count = (haystack: string, needle: string): number => haystack.split(needle).length - 1;

export function validate(name: FieldName, value: string): string | null {
  const f = FIELDS[name];
  if (value === f.placeholder) return `${f.env} still holds the placeholder value`;
  if (!f.pattern.test(value)) return `${f.env} must be ${f.hint}`;
  return null;
}

export function renderConfig(
  template: string,
  expected: Partial<Record<FieldName, number>>,
  values: Partial<Record<FieldName, string>>,
): string {
  const errors: string[] = [];

  for (const name of FIELD_NAMES) {
    const found = count(template, FIELDS[name].placeholder);
    const want = expected[name] ?? 0;
    if (found !== want) {
      errors.push(`Template drift: ${name} placeholder appears ${found} time(s), expected ${want}`);
    }
  }

  let out = template;
  for (const name of Object.keys(expected) as FieldName[]) {
    const value = values[name];
    if (value === undefined) {
      errors.push(`${FIELDS[name].env} is not set`);
      continue;
    }
    const problem = validate(name, value);
    if (problem) {
      errors.push(problem);
      continue;
    }
    out = out.replaceAll(FIELDS[name].placeholder, value);
  }

  if (errors.length > 0) throw new Error(errors.join("\n"));

  for (const name of FIELD_NAMES) {
    if (out.includes(FIELDS[name].placeholder)) {
      throw new Error(`Template drift: ${name} placeholder survived substitution`);
    }
  }
  return `// GENERATED by scripts/generate-deploy-config.ts — do not edit. Edit wrangler.jsonc instead.\n${out}`;
}
